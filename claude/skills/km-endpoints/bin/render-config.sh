#!/bin/bash
# Render a multi-profile ~/.config/komodo/komodo.cli.toml from every
# external inventory <name>.toml. Each endpoint becomes a [[profile]] block
# whose `name` equals the endpoint filename. The km CLI then selects
# per invocation via `km -p <name>`.
#
# This script is the only writer of ~/.config/komodo/komodo.cli.toml.
# Two concurrent shells can each run `km -p homelab` and `km -p trading`
# without touching this file — that is the whole point of the redesign.
# Re-run only when the external endpoint inventory changes.
set -euo pipefail

ENDPOINTS_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/komodo/endpoints"
KM_CONFIG="$HOME/.config/komodo/komodo.cli.toml"

shopt -s nullglob
endpoints=("$ENDPOINTS_DIR"/*.toml)
shopt -u nullglob

if [ "${#endpoints[@]}" -eq 0 ]; then
    echo "ERROR: no endpoints in $ENDPOINTS_DIR" >&2
    exit 1
fi

mkdir -p "$(dirname "$KM_CONFIG")"

tmp="$(mktemp "${KM_CONFIG}.XXXXXX")"
trap 'rm -f "$tmp"' EXIT

# Pick first endpoint as default_profile so a bare `km` invocation is
# still legal (it lands on whichever profile sorts first). Every real
# call should pass -p explicitly; default_profile is a syntactic
# fallback, not a behavioral contract.
default_name="$(basename "${endpoints[0]}" .toml)"

{
    echo "# AUTO-GENERATED by km-endpoints/bin/render-config.sh"
    echo "# Source of truth: $ENDPOINTS_DIR/*.toml"
    echo "# Re-render with: bash ~/.claude/skills/km-endpoints/bin/render-config.sh"
    echo "# Do not hand-edit — your changes will be lost on next render."
    echo
    echo "default_profile = \"$default_name\""
    for f in "${endpoints[@]}"; do
        name="$(basename "$f" .toml)"
        for k in host key secret; do
            if ! grep -qE "^${k}\\s*=" "$f"; then
                echo "ERROR: $f missing required key '$k'" >&2
                exit 1
            fi
        done
        echo
        echo "[[profile]]"
        echo "name = \"$name\""
        cat "$f"
    done
} > "$tmp"

mv "$tmp" "$KM_CONFIG"
trap - EXIT

echo "Rendered $KM_CONFIG with ${#endpoints[@]} profile(s):"
for f in "${endpoints[@]}"; do
    echo "  - $(basename "$f" .toml)"
done
